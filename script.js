/*
 * ============================================================
 * Nächster Eintrag
 * ============================================================
 */

function nextWord() {

  const topic =
    document.getElementById(
      "topicSelect"
    ).value;


  /*
   * ALL
   */

  if (topic === "all") {

    if (
      allHistoryIndex
      <
      allHistory.length - 1
    ) {

      allHistoryIndex++;

    } else {

      if (!addRandomAllEntry()) {

        return;

      }

    }


    showCurrentWord();


    document.getElementById(
      "feedbackArea"
    ).innerText = "";


    return;

  }


  /*
   * Einzelnes Thema
   */

  const currentArray =
    getCurrentArray();


  if (currentArray.length === 0) {

    showEmptyMessage();

    return;

  }


  currentWordIndex =
    (
      currentWordIndex + 1
    )
    %
    currentArray.length;


  showCurrentWord();


  document.getElementById(
    "feedbackArea"
  ).innerText = "";

}


/*
 * ============================================================
 * Vorheriger Eintrag
 * ============================================================
 */

function prevWord() {

  const topic =
    document.getElementById(
      "topicSelect"
    ).value;


  /*
   * ALL
   */

  if (topic === "all") {

    if (allHistoryIndex > 0) {

      allHistoryIndex--;

      showCurrentWord();

    }


    document.getElementById(
      "feedbackArea"
    ).innerText = "";


    return;

  }


  /*
   * Einzelnes Thema
   */

  const currentArray =
    getCurrentArray();


  if (currentArray.length === 0) {

    showEmptyMessage();

    return;

  }


  currentWordIndex =
    (
      currentWordIndex
      - 1
      + currentArray.length
    )
    %
    currentArray.length;


  showCurrentWord();


  document.getElementById(
    "feedbackArea"
  ).innerText = "";

}


