function checkTranslation() {

  const topic =
    document.getElementById(
      "topicSelect"
    ).value;


  /*
   * ALL
   */

  if (topic === "all") {

    if (allHistoryIndex < 0) {

      return;

    }


    const entry =
      allHistory[
        allHistoryIndex
      ];


    document.getElementById(
      "feedbackArea"
    ).innerText =
      entry.language === "en"
        ? entry.word.de
        : entry.word.en;


    return;

  }


  /*
   * Einzelnes Thema
   */

  const currentArray =
    getCurrentArray();


  if (currentArray.length === 0) {

    showEmptyMessage();

    return;

  }


  const word =
    currentArray[
      currentWordIndex
    ];


  const direction =
    getDirection();


  document.getElementById(
    "feedbackArea"
  ).innerText =
    direction === "en-de"
      ? word.de
      : word.en;

}


/*
 * ============================================================
 * Gesamttabelle erzeugen
 * ============================================================
 */

function buildOverviewTable() {

  const table =
    document.getElementById(
      "overviewTable"
    );


  const topicSelect =
    document.getElementById(
      "topicSelect"
    );


  table.innerHTML = "";


  Array.from(
    topicSelect.options
  ).forEach(option => {

    const topicKey = option.value;


    if (topicKey === "all") {

      return;

    }


    const words =
      topicsWords[topicKey] || [];


    const sentences =
      topicsSentences[topicKey] || [];


    const entries = [
      ...words,
      ...sentences
    ];


    if (entries.length === 0) {

      return;

    }


    const topicRow =
      document.createElement(
        "tr"
      );


    topicRow.className =
      "topic-row";


    topicRow.innerHTML = `
      <th class="topic-name">${option.textContent}</th>
      <th class="language-head">Englisch</th>
      <th class="language-head">Deutsch</th>
    `;


    table.appendChild(
      topicRow
    );


    entries.forEach(entry => {

      const row =
        document.createElement(
          "tr"
        );


      const emptyCell =
        document.createElement(
          "td"
        );


      emptyCell.className =
        "empty-topic-cell";


      const englishCell =
        document.createElement(
          "td"
        );


      englishCell.textContent =
        entry.en;


      const germanCell =
        document.createElement(
          "td"
        );


      germanCell.textContent =
        entry.de;


      row.appendChild(
        emptyCell
      );


      row.appendChild(
        englishCell
      );


      row.appendChild(
        germanCell
      );


      table.appendChild(
        row
      );

    });

  });

}


